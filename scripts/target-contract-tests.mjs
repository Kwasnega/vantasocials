import assert from "node:assert/strict";
import fs from "node:fs";
import { effectiveQuantityBounds, getTargetContract, normalizeTarget } from "../lib/targets/contracts.ts";
import { assessProviderEligibility } from "../lib/targets/eligibility.ts";
import { effectiveQuantityRange, quantityInRange } from "../lib/targets/quantity.ts";

assert.equal(getTargetContract("instagram-views"), "INSTAGRAM_CONTENT");
assert.equal(getTargetContract("telegram-post-views"), null);
assert.equal(normalizeTarget("instagram-followers", "@User").target, "https://www.instagram.com/User");
assert.equal(normalizeTarget("instagram-followers", "user").target, "https://www.instagram.com/user");
assert.equal(normalizeTarget("instagram-followers", "https://instagram.com/user/").target, "https://instagram.com/user");
assert.equal(normalizeTarget("instagram-followers", "https://instagram.com/p/post").valid, false);
assert.equal(normalizeTarget("instagram-likes", "@user").valid, false);
assert.equal(normalizeTarget("instagram-views", "https://www.instagram.com/p/abc/").target, "https://www.instagram.com/p/abc");
assert.equal(normalizeTarget("instagram-views", "https://www.instagram.com/reel/abc").valid, true);
assert.equal(normalizeTarget("tiktok-followers", "@user").target, "https://www.tiktok.com/@user");
assert.equal(normalizeTarget("tiktok-views", "https://www.tiktok.com/@user/video/123").valid, true);
assert.equal(normalizeTarget("tiktok-views", "https://www.tiktok.com/@user").valid, false);
assert.equal(normalizeTarget("youtube-subscribers", "https://www.youtube.com/@creator").valid, true);
assert.equal(normalizeTarget("youtube-subscribers", "creator").valid, false);
assert.equal(normalizeTarget("youtube-likes", "https://www.youtube.com/watch?v=abc").valid, true);
assert.equal(normalizeTarget("youtube-subscribers", "https://www.youtube.com/watch?v=abc").valid, false);
assert.equal(normalizeTarget("facebook-page-followers", "https://www.facebook.com/page").valid, true);
assert.equal(normalizeTarget("facebook-page-followers", "https://www.facebook.com/page/posts/1").valid, false);
assert.equal(normalizeTarget("facebook-post-likes", "https://www.facebook.com/page/posts/1").valid, true);
assert.equal(normalizeTarget("facebook-video-views", "https://www.facebook.com/reel/1").valid, true);
assert.equal(normalizeTarget("instagram-views", "https://evil.instagram.com/p/abc").valid, false);
assert.equal(normalizeTarget("youtube-subscribers", "https://attacker.youtube.com/@creator").valid, false);
assert.equal(normalizeTarget("facebook-page-followers", "https://evil.facebook.com/page").valid, false);
assert.equal(normalizeTarget("tiktok-followers", "https://fake.tiktok.com/@user").valid, false);
assert.equal(normalizeTarget("instagram-views", "https://www.instagram.com/p/abc?utm_source=x").target, "https://www.instagram.com/p/abc?utm_source=x");
assert.equal(normalizeTarget("youtube-likes", "https://www.youtube.com/watch?v=abc&utm_source=x").target, "https://www.youtube.com/watch?v=abc");
assert.deepEqual(effectiveQuantityBounds(100, 100000, 100, 10000), { min: 100, max: 10000 });
assert.deepEqual(effectiveQuantityBounds(100, 100000, 1000, 50000), { min: 1000, max: 50000 });
const provider = { provider: "reliablesmm", provider_service_id: "7486", name: "Instagram Video Views", provider_status: "ACTIVE", provider_currency: "USD", rate_unit: "PER_1000", min_quantity: 100, max_quantity: 10000 };
assert.equal(assessProviderEligibility({ serviceSlug: "instagram-views", targetContract: "INSTAGRAM_CONTENT", vantaMin: 100, vantaMax: 100000, provider }).status, "ELIGIBLE");
assert.equal(assessProviderEligibility({ serviceSlug: "instagram-followers", targetContract: "INSTAGRAM_PROFILE", vantaMin: 100, vantaMax: 100000, provider: { ...provider, provider_service_id: "7972", name: "Instagram Followers" } }).status, "MANUAL_REVIEW");
assert.equal(assessProviderEligibility({ serviceSlug: "instagram-comments", targetContract: null, vantaMin: 100, vantaMax: 100000, provider: { ...provider, provider_service_id: "7856", name: "Custom Comments" } }).status, "BLOCKED");
assert.equal(assessProviderEligibility({ serviceSlug: "facebook-page-likes", targetContract: null, vantaMin: 100, vantaMax: 100000, provider: { ...provider, provider_service_id: "7099", name: "Facebook Post Likes" } }).status, "BLOCKED");
assert.equal(assessProviderEligibility({ serviceSlug: "x-reposts", targetContract: null, vantaMin: 1, vantaMax: 100000, provider: { ...provider, provider_service_id: "" } }).status, "BLOCKED");
assert.deepEqual(effectiveQuantityRange(100, 100000, 100, 10000), { min: 100, max: 10000 });
assert.equal(quantityInRange(100, { min: 100, max: 10000 }), true);
assert.equal(quantityInRange(10000, { min: 100, max: 10000 }), true);
assert.equal(quantityInRange(10001, { min: 100, max: 10000 }), false);
assert.equal(quantityInRange(50000, { min: 100, max: 10000 }), false);
assert.equal(quantityInRange(100000, effectiveQuantityRange(100, 100000)), true);

